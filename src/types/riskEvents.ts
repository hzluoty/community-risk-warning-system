export type EventGrade = 'Normal' | 'C' | 'B' | 'A';
export type EventLifecycle = 'pending' | 'active' | 'observationally_cleared' | 'ended_unresolved';
export type ObservationHealth = 'fresh' | 'unknown' | 'failure' | 'stale' | 'review';
export type RiskCategory = 'fire' | 'security' | 'assistance' | 'environment' | 'facility';
export interface EventBox { x: number; y: number; width: number; height: number }
export interface SemanticScores { consequence: number; exposure: number; urgency: number }
export interface EventCandidate {
  id: string;
  category: RiskCategory;
  subtype: string;
  confidence: number;
  scores: SemanticScores;
  observation: string;
  evidenceFrameIds: string[];
  box: EventBox;
  regionId: string | null;
}
export interface EventCheck {
  eventId: string;
  verdict: 'present' | 'absent' | 'unknown';
  regionVisible: boolean;
  evidenceFrameIds: string[];
}
export interface EventModelOutput {
  quality: 'clear' | 'uncertain';
  summary: string;
  candidates: EventCandidate[];
  eventChecks: EventCheck[];
}
/** Generated by the host, never accepted from model text. Monotonic values are session-local. */
export interface EventFrameContext {
  cameraId: string;
  frameId: string;
  sequence: number;
  capturedAt: number;
  capturedMonotonicAt: number;
  sessionId: string;
  modelVersion: string;
}
export interface EventObservation {
  context: EventFrameContext;
  receivedMonotonicAt: number;
  status: 'ok' | 'failure';
  output?: EventModelOutput;
}
export interface RegisteredRegion {
  id: string;
  cameraId: string;
  box: EventBox;
  sceneFactor: number;
  environment: number | null;
}
export interface DecisionConfig {
  version: string;
  freshMs: number;
  gapMs: number;
  confidence: number;
  iouThreshold: number;
  regions: RegisteredRegion[];
  historyWindowMs: number;
  historyDecayMs: number;
  historyWeight: number;
}
export interface DecisionEvent {
  id: string;
  cameraId: string;
  category: RiskCategory;
  subtype: string;
  regionId: string | null;
  box: EventBox;
  grade: EventGrade;
  lifecycle: EventLifecycle;
  health: ObservationHealth;
  handling: 'pending' | 'processing' | 'done';
  confirmedAt: number | null;
  createdAt: number;
  updatedAt: number;
  sessionId: string;
  lastPositiveMono: number;
  lastValidMono: number;
  segmentStartMono: number | null;
  previousScore: number | null;
  downCount: number;
  absentCount: number;
  score: number;
  confidence: number;
  modelVersion: string;
  baseScore: number;
  historyTerm: number;
  environmentMissing: boolean;
  observation: string;
  lastFrameId: string;
  firstAlert: boolean;
  configVersion: string;
}
export interface DecisionAudit {
  frameId: string;
  cameraId: string;
  reason: string;
}
export interface DecisionState {
  events: DecisionEvent[];
  watermarks: Record<string, number>;
  audit: DecisionAudit[];
  review: { frameId: string; candidateId: string; reason: string }[];
  nextId: number;
}
